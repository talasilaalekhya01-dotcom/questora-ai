def find_robot_file():
    project_root = Path(__file__).resolve().parent
    assets_folder = project_root / "assets"

    exact_robot = assets_folder / "cute_round_robot_with_big_eyes_small_limbs. (1).glb"
    if exact_robot.exists():
        return exact_robot

    renamed_robot = assets_folder / "robot.glb"
    if renamed_robot.exists():
        return renamed_robot

    if assets_folder.exists():
        glb_files = list(assets_folder.glob("*.glb"))
        if glb_files:
            return glb_files[0]

    # Helpful fallback for local testing if the file sits beside app.py.
    fallback = project_root / "cute_round_robot_with_big_eyes_small_limbs. (1).glb"
    if fallback.exists():
        return fallback

    return None


def markdown_inline(text: str):
    text = html_lib.escape(text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)
    text = re.sub(r"(?<!\*)\*([^*]+?)\*(?!\*)", r"<i>\1</i>", text)
    text = re.sub(r"`([^`]+?)`", r"<font name='Courier'>\1</font>", text)
    return text


def create_pdf_report(report_text: str, title: str = "Questora AI Research Report"):
    buffer = BytesIO()
    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=45,
        rightMargin=45,
        topMargin=50,
        bottomMargin=50,
        title=title,
        author="Questora AI",
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "QuestoraTitle",
        parent=styles["Title"],
        fontName="Helvetica-Bold",
        fontSize=22,
        leading=28,
        alignment=TA_CENTER,
        spaceAfter=8,
    )

    subtitle_style = ParagraphStyle(
        "QuestoraSubtitle",
        parent=styles["BodyText"],
        fontName="Helvetica",
        fontSize=9,
        alignment=TA_CENTER,
        textColor=colors.HexColor("#666666"),
        spaceAfter=18,
    )

    heading1 = ParagraphStyle(
        "QuestoraH1",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=16,
        leading=21,
        spaceBefore=12,
        spaceAfter=8,
    )

    heading2 = ParagraphStyle(
        "QuestoraH2",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=18,
        spaceBefore=10,
        spaceAfter=6,
    )

    heading3 = ParagraphStyle(
        "QuestoraH3",
        parent=styles["Heading3"],
        fontName="Helvetica-Bold",
        fontSize=11,
        leading=16,
        spaceBefore=8,
        spaceAfter=5,
    )

    body_style = ParagraphStyle(
        "QuestoraBody",
        parent=styles["BodyText"],
        fontName="Helvetica",
        fontSize=10,
        leading=15,
        textColor=colors.HexColor("#222222"),
        spaceAfter=7,
    )

    bullet_style = ParagraphStyle(
        "QuestoraBullet",
        parent=body_style,
        leftIndent=18,
        firstLineIndent=-8,
        spaceAfter=5,
    )

    story = [
        Paragraph(markdown_inline(title), title_style),
        Paragraph(
            "Generated by Questora AI - Multi-Agent Research Assistant",
            subtitle_style,
        ),
        HRFlowable(
            width="100%",
            thickness=0.7,
            color=colors.HexColor("#BBBBBB"),
            spaceAfter=14,
        ),
    ]

    for raw_line in report_text.splitlines():
        line = raw_line.strip()

        if not line:
            story.append(Spacer(1, 5))
        elif line.startswith("### "):
            story.append(Paragraph(markdown_inline(line[4:]), heading3))
        elif line.startswith("## "):
            story.append(Paragraph(markdown_inline(line[3:]), heading2))
        elif line.startswith("# "):
            story.append(Paragraph(markdown_inline(line[2:]), heading1))
        elif line.startswith(("- ", "* ")):
            story.append(Paragraph("• " + markdown_inline(line[2:]), bullet_style))
        else:
            story.append(Paragraph(markdown_inline(line), body_style))

    document.build(story)
    pdf_data = buffer.getvalue()
    buffer.close()
    return pdf_data


