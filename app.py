def hex_points(cx, cy, radius=31):
    points = [
        (cx, cy - radius),
        (cx + radius * .866, cy - radius / 2),
        (cx + radius * .866, cy + radius / 2),
        (cx, cy + radius),
        (cx - radius * .866, cy + radius / 2),
        (cx - radius * .866, cy - radius / 2),
    ]
    return " ".join(f"{x:.1f},{y:.1f}" for x, y in points)


